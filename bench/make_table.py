#!/usr/bin/env python
"""Regenerate bench/RESULTS.md from bench/results/*.json (no hand-typed numbers)."""
import glob, json, os
H = os.path.dirname(os.path.abspath(__file__))
rows = ["| file | model | mode | beam | clip | WER | CER | RTF |", "|---|---|---|---|---|---|---|---|"]
for f in sorted(glob.glob(os.path.join(H, "results", "*.json"))):
    r = json.load(open(f)); mode = r["mode"] + (f" cap{int(r['cap'])}" if r.get("cap") else "")
    for c in r["clips"]:
        rows.append(f"| {os.path.basename(f)} | {r['model_tag']} | {mode} | {r['beam']} | {c['clip']} | {c['wer']:.3f} | {c['cer']:.3f} | {c['rtf']:.2f} |")
open(os.path.join(H, "RESULTS.md"), "w").write("# Results (generated by bench/make_table.py; do not edit)\n\nSTT stage only, CPU int8. WER/CER normalisation in bench/metrics.py.\n\n" + "\n".join(rows) + "\n")
print(len(rows) - 2, "rows")
