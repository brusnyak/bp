/* Capability adapter: the one place the UI learns which languages and routes exist.
   Order of trust: GET /api/capabilities (target contract) -> GET /api/routes (today) -> /ui/shared/manifest.json
   (generated by scripts/ui_manifest.py). No language list lives in any page.

   Route: { pair, source, target, tier, voice, reason }
   tier:  'speech'   STT + MT + voice present      'captions' STT + MT, no voice
          'setup'    declared, assets missing      'declared' only a manifest is known (server unreachable)   */
(function () {
  'use strict';

  var TIER_ORDER = { speech: 0, captions: 1, setup: 2, declared: 3 };
  var TIER_LABEL = {
    speech: 'Speech and captions', captions: 'Captions only',
    setup: 'Needs setup', declared: 'Declared, not checked'
  };
  var pending = null;

  function getJson(url) {
    return fetch(url, { cache: 'no-store' }).then(function (r) {
      if (!r.ok) throw new Error(url + ' ' + r.status);
      return r.json();
    });
  }

  function fromRoutes(inv) {
    return (inv.routes || []).map(function (r) {
      var a = r.assets || {};
      var tier = a.resolved && a.tts ? 'speech' : (a.stt && a.mt ? 'captions' : 'setup');
      return { pair: r.pair, source: r.source, target: r.target, tier: tier, voice: a.tts || null,
               reason: (a.errors && a.errors[0]) || '' };
    });
  }

  function fromCapabilities(c) {
    return (c.routes || []).map(function (r) {
      return { pair: r.pair, source: r.source, target: r.target, tier: r.tier || 'setup',
               voice: r.voice || null, reason: r.reason || '' };
    });
  }

  function fromManifest(m) {
    return (m.routes || []).map(function (r) {
      return { pair: r.pair, source: r.source, target: r.target, tier: 'declared', voice: r.tts || null, reason: '' };
    });
  }

  function token() { try { return localStorage.getItem('userToken') || ''; } catch (e) { return ''; } }
  function authed(url) {
    var t = token();
    return fetch(url, { cache: 'no-store', headers: t ? { Authorization: 'Bearer ' + t } : {} })
      .then(function (r) { if (!r.ok) throw new Error(url + ' ' + r.status); return r.json(); });
  }

  function build(routes, source) {
    routes.sort(function (a, b) { return TIER_ORDER[a.tier] - TIER_ORDER[b.tier] || a.pair.localeCompare(b.pair); });
    return {
      source: source, routes: routes,
      /* languages you can speak (source side), or those a given source can be translated into */
      sources: function () { return uniq(routes.map(function (r) { return r.source; })); },
      targets: function (src) { return uniq(routes.filter(function (r) { return !src || r.source === src; })
                                                  .map(function (r) { return r.target; })); },
      route: function (src, tgt) { return routes.find(function (r) { return r.source === src && r.target === tgt; }) || null; },
      /* best tier a language reaches in the given role */
      tierOf: function (code, role) {
        var best = 'declared', found = false;
        routes.forEach(function (r) {
          if ((role === 'source' ? r.source : r.target) !== code) return;
          found = true; if (TIER_ORDER[r.tier] < TIER_ORDER[best]) best = r.tier;
        });
        return found ? best : null;
      }
    };
  }

  function uniq(a) { return a.filter(function (x, i) { return a.indexOf(x) === i; }); }

  function load() {
    if (pending) return pending;
    pending = authed('/api/capabilities').then(function (c) { return build(fromCapabilities(c), 'capabilities'); })
      .catch(function () { return authed('/api/routes').then(function (r) { return build(fromRoutes(r), 'routes'); }); })
      .catch(function () { return getJson('/ui/shared/manifest.json').then(function (m) { return build(fromManifest(m), 'manifest'); }); })
      .catch(function () { return build([], 'none'); });
    return pending;
  }

  /* Names: native first, then the name in the page language. Browser-built, so a new code needs no dictionary. */
  var dn = {};
  function names(code, inLocale) {
    var base = code.replace('_', '-');
    var key = inLocale || 'en';
    try {
      dn[key] = dn[key] || new Intl.DisplayNames([key], { type: 'language' });
      dn[base] = dn[base] || new Intl.DisplayNames([base], { type: 'language' });
      var native = dn[base].of(base) || code, local = dn[key].of(base) || code;
      return { native: native.charAt(0).toLocaleUpperCase(base) + native.slice(1), local: local };
    } catch (e) { return { native: code, local: code }; }
  }

  window.caps = { load: load, names: names, TIER_LABEL: TIER_LABEL, TIER_ORDER: TIER_ORDER };
})();
